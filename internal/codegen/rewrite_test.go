func TestSetPackageName(t *testing.T) {
	t.Parallel()

	t.Run("replaces the name and nothing else", func(t *testing.T) {
		t.Parallel()

		src := "// Code generated by tutone: DO NOT EDIT\n//go:build integration\n\npackage scorecards // the folder's name\n\nfunc scorecards() {}\n"

		out, err := SetPackageName([]byte(src), "servicearchintelligence")
		require.NoError(t, err)
		assert.Equal(t, "// Code generated by tutone: DO NOT EDIT\n//go:build integration\n\npackage servicearchintelligence // the folder's name\n\nfunc scorecards() {}\n", string(out))
	})

	t.Run("the same name is left as it is", func(t *testing.T) {
		t.Parallel()

		src := []byte("package demo\n\nfunc broken( {")

		out, err := SetPackageName(src, "demo")
		require.NoError(t, err, "only the clause is parsed")
		assert.Equal(t, src, out)
	})

	t.Run("source that is incomplete after the clause is fine", func(t *testing.T) {
		t.Parallel()

		out, err := SetPackageName([]byte("package demo\n\nfunc broken( {"), "other")
		require.NoError(t, err)
		assert.Equal(t, "package other\n\nfunc broken( {", string(out))
	})

	t.Run("source without a package clause is an error", func(t *testing.T) {
		t.Parallel()

		_, err := SetPackageName([]byte("func f() {}\n"), "demo")
		require.Error(t, err)
	})
}

func TestRenameReceivers(t *testing.T) {
	t.Parallel()

	renames := map[string]string{"Organization": "OrganizationManagement"}

	t.Run("pointer, value, parenthesised and generic receivers", func(t *testing.T) {
		t.Parallel()

		src := `package organization

func (a *Organization) Pointer() {}
func (a Organization) Value() {}
func (a (*Organization)) Parens() {}
func (a *Organization[T]) One() {}
func (a *Organization[K, V]) Two() {}
func (*Organization) Unnamed() {}
`
		out, err := RenameReceivers([]byte(src), renames)
		require.NoError(t, err)

		assert.Equal(t, `package organization

func (a *OrganizationManagement) Pointer() {}
func (a OrganizationManagement) Value() {}
func (a (*OrganizationManagement)) Parens() {}
func (a *OrganizationManagement[T]) One() {}
func (a *OrganizationManagement[K, V]) Two() {}
func (*OrganizationManagement) Unnamed() {}
`, string(out))
	})

	t.Run("only receivers change", func(t *testing.T) {
		t.Parallel()

		src := `package organization

// Organization is the client.
type Organization struct{ client Client }

type Holder struct{ org *Organization }

var _ = &Organization{}

const Organization2 = "Organization"

// Organization.Get is documented here.
func (a *Organization) Get(other *Organization) *Organization {
	var o Organization
	_ = o
	return other.Self() // Organization
}

func (a *Holder) Organization() *Organization { return a.org }

func Organization3(o Organization) {}
`
		out, err := RenameReceivers([]byte(src), renames)
		require.NoError(t, err)

		want := `package organization

// Organization is the client.
type Organization struct{ client Client }

type Holder struct{ org *Organization }

var _ = &Organization{}

const Organization2 = "Organization"

// Organization.Get is documented here.
func (a *OrganizationManagement) Get(other *Organization) *Organization {
	var o Organization
	_ = o
	return other.Self() // Organization
}

func (a *Holder) Organization() *Organization { return a.org }

func Organization3(o Organization) {}
`
		assert.Equal(t, want, string(out))
	})

	t.Run("a receiver of another type is left alone", func(t *testing.T) {
		t.Parallel()

		src := "package p\n\nfunc (x *Widget) Get() {}\n"

		out, err := RenameReceivers([]byte(src), renames)
		require.NoError(t, err)
		assert.Equal(t, src, string(out))
	})

	t.Run("no renames, or a rename to the same name, changes nothing", func(t *testing.T) {
		t.Parallel()

		src := "package p\n\nfunc (a *Organization) Get() {}\n"

		out, err := RenameReceivers([]byte(src), nil)
		require.NoError(t, err)
		assert.Equal(t, src, string(out))

		out, err = RenameReceivers([]byte(src), map[string]string{"Organization": "Organization"})
		require.NoError(t, err)
		assert.Equal(t, src, string(out))
	})

	t.Run("source that does not parse is an error", func(t *testing.T) {
		t.Parallel()

		_, err := RenameReceivers([]byte("package p\n\nfunc broken( {"), renames)
		require.Error(t, err)
	})
}

