func TestMergeHandWritten_MethodsAreKeyedByReceiver(t *testing.T) {
	t.Parallel()

	generated := "package demo\n\ntype A struct{}\ntype B struct{}\n\nfunc (a *A) Get() int { return 1 }\n"
	existing := "package demo\n\ntype A struct{}\ntype B struct{}\n\nfunc (a *A) Get() int { return 0 }\n\nfunc (b *B) Get() int { return 2 }\n"

	out, kept := merge(t, generated, existing)

	// A.Get is the generator's; B.Get is not, so it survives.
	assert.Equal(t, []string{"B.Get"}, kept)
	assert.Contains(t, out, "return 1")
	assert.Contains(t, out, "return 2")
	assert.NotContains(t, out, "return 0")
}

func TestMergeHandWritten_TypesConstsAndVarsShareANamespace(t *testing.T) {
	t.Parallel()

	generated := "package demo\n\ntype Same struct{}\n"
	existing := "package demo\n\nvar Same = 1\n"

	out, kept := merge(t, generated, existing)

	assert.Empty(t, kept, "a var with the generator's type name would not compile, so it is the generator's name")
	assert.NotContains(t, out, "var Same")
}

func TestMergeHandWritten_CarriesImportsTheKeptCodeNeeds(t *testing.T) {
	t.Parallel()

	generated := "package demo\n\nimport \"fmt\"\n\nfunc Gen() { fmt.Println() }\n"
	existing := "package demo\n\nimport (\n\t\"fmt\"\n\t\"strings\"\n\tsl \"sort\"\n)\n\nfunc Hand() string { sl.Strings(nil); return strings.ToUpper(\"x\") }\n"

	out, _ := merge(t, generated, existing)

	assert.Contains(t, out, `"strings"`)
	assert.Contains(t, out, `sl "sort"`)
	assert.Equal(t, 1, strings.Count(out, `"fmt"`), "an import both files have is not repeated")
}

