const generatedSrc = `// Code generated by tutone: DO NOT EDIT
package demo

import "fmt"

// Widget is generated.
type Widget struct {
	Name string
}

// GetWidget is generated.
func (a *Client) GetWidget() string {
	return fmt.Sprint("generated")
}

const widgetQuery = "generated"
`

func merge(t *testing.T, generated, existing string) (string, []string) {
	t.Helper()

	out, kept, err := MergeHandWritten([]byte(generated), []byte(existing))
	require.NoError(t, err)

	// Whatever comes out must still be valid Go.
	_, parseErr := parser.ParseFile(token.NewFileSet(), "out.go", out, parser.ParseComments)
	require.NoError(t, parseErr, "merged output must parse:\n%s", out)

	return string(out), kept
}

func TestMergeHandWritten_KeepsDeclarationsTheGeneratorDoesNotProduce(t *testing.T) {
	t.Parallel()

	existing := `package demo

import "fmt"

type Widget struct {
	Name string
}

// GetAccountsMinimized was added by hand.
func (a *Client) GetAccountsMinimized() string {
	return fmt.Sprint("hand")
}

type HandType struct{ X int }

var handVar = 1
`

	out, kept := merge(t, generatedSrc, existing)

	assert.Contains(t, out, "GetAccountsMinimized")
	assert.Contains(t, out, "type HandType struct")
	assert.Contains(t, out, "var handVar = 1")
	assert.ElementsMatch(t, []string{"Client.GetAccountsMinimized", "HandType", "handVar"}, kept)

	// The generator's own declarations come from the new output.
	assert.Contains(t, out, "// GetWidget is generated.")
	assert.Equal(t, 1, strings.Count(out, "type Widget struct"))
}

func TestMergeHandWritten_GeneratedDeclarationsAreReplacedNotKept(t *testing.T) {
	t.Parallel()

	existing := `package demo

import "fmt"

type Widget struct {
	Name  string
	Stale string
}

func (a *Client) GetWidget() string {
	return fmt.Sprint("old generated version")
}

const widgetQuery = "old"
`

	out, kept := merge(t, generatedSrc, existing)

	assert.Empty(t, kept)
	assert.NotContains(t, out, "Stale")
	assert.NotContains(t, out, "old generated version")
	assert.NotContains(t, out, `"old"`)
}

func TestMergeHandWritten_DoNotRegenerateKeepsTheExistingTextInPlace(t *testing.T) {
	t.Parallel()

	existing := `package demo

import "fmt"

type Widget struct {
	Name string
}

// GetWidget has a timestamp fix.
// DO NOT REGENERATE
func (a *Client) GetWidget() string {
	return fmt.Sprint("hand fixed")
}
`

	out, kept := merge(t, generatedSrc, existing)

	assert.Contains(t, out, "hand fixed")
	assert.NotContains(t, out, `fmt.Sprint("generated")`)
	assert.Equal(t, 1, strings.Count(out, "func (a *Client) GetWidget"))
	assert.Equal(t, []string{"Client.GetWidget"}, kept)

	// In place, not moved to the end: it still sits between the type and the const.
	assert.Less(t, strings.Index(out, "type Widget"), strings.Index(out, "hand fixed"))
	assert.Less(t, strings.Index(out, "hand fixed"), strings.Index(out, "const widgetQuery"))
}

