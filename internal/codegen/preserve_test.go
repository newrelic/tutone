type fakeGenerator struct{ Name string }

func (fakeGenerator) Generate(*schema.Schema, *config.GeneratorConfig, *config.PackageConfig) error {
	return nil
}
func (fakeGenerator) Execute(*config.GeneratorConfig, *config.PackageConfig) error { return nil }

func writeTemplate(t *testing.T, body string) (dir, name string) {
	t.Helper()

	dir = t.TempDir()
	name = "t.go.tmpl"
	require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(body), 0o600))

	return dir, name
}

func TestWriteFile_PreservesHandWrittenAcrossRegeneration(t *testing.T) {
	t.Parallel()

	tmplDir, tmplName := writeTemplate(t, "package demo\n\ntype {{.Name}} struct{}\n")
	out := t.TempDir()
	dest := filepath.Join(out, "types.go")

	require.NoError(t, os.WriteFile(dest, []byte("package demo\n\ntype Old struct{}\n\n// HandWritten stays.\nfunc HandWritten() {}\n"), 0o600))

	c := CodeGen{
		TemplateDir:         tmplDir,
		TemplateName:        tmplName,
		DestinationDir:      out,
		DestinationFile:     dest,
		PreserveHandWritten: true,
	}
	require.NoError(t, c.WriteFile(fakeGenerator{Name: "Fresh"}))

	got, err := os.ReadFile(dest)
	require.NoError(t, err)

	assert.Contains(t, string(got), "type Fresh struct")
	assert.Contains(t, string(got), "func HandWritten()")

	// A declaration the generator used to produce and no longer does cannot be told
	// apart from hand-written code, so it stays. preserve_hand_written: false
	// (the next test) is how a package opts out and drops such leftovers.
	assert.Contains(t, string(got), "type Old struct")
}

