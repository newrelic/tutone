func scalar(name string) schema.TypeRef { return schema.TypeRef{Kind: schema.KindScalar, Name: name} }

// widgetSchema has a struct, a second struct and an enum, each with a few members.
func widgetSchema() *schema.Schema {
	return &schema.Schema{
		MutationType: &schema.Type{Name: "RootMutationType", Kind: schema.KindObject},
		Types: []*schema.Type{
			{Name: "Widget", Kind: schema.KindObject, Fields: []schema.Field{
				{Name: "name", Type: scalar("String")},
				{Name: "size", Type: scalar("Int")},
			}},
			{Name: "Gadget", Kind: schema.KindObject, Fields: []schema.Field{
				{Name: "name", Type: scalar("String")},
			}},
			{Name: "Color", Kind: schema.KindENUM, EnumValues: []schema.EnumValue{
				{Name: "BLUE"},
				{Name: "RED"},
			}},
			{Name: "Int", Kind: schema.KindScalar},
			{Name: "String", Kind: schema.KindScalar},
		},
	}
}

// existingTypes was generated from an older schema: Widget had a color and a
// different type for size, Color had AMBER, and Gadget had a weight.
const existingTypes = `// Code generated by tutone: DO NOT EDIT
package demo

type Color string

var ColorTypes = struct {
	AMBER Color
	BLUE  Color
	RED   Color
}{
	AMBER: "AMBER",
	BLUE:  "BLUE",
	RED:   "RED",
}

type Gadget struct {
	Name   string ` + "`json:\"name,omitempty\"`" + `
	Weight int    ` + "`json:\"weight,omitempty\"`" + `
}

type Widget struct {
	Color string ` + "`json:\"color,omitempty\"`" + `
	Name  string ` + "`json:\"name,omitempty\"`" + `
	Size  string ` + "`json:\"size,omitempty\"`" + `
}
`

func regenerate(t *testing.T, existing string, pkg config.PackageConfig) string {
	t.Helper()

	dir := t.TempDir()
	pkg.Name = "demo"
	pkg.Path = dir

	if existing != "" {
		require.NoError(t, os.WriteFile(filepath.Join(dir, "types.go"), []byte(existing), 0o600))
	}

	gc := &config.GeneratorConfig{Name: "typegen", FileName: "types.go", TemplateDir: "../../templates/typegen"}
	g := &Generator{}

	require.NoError(t, g.Generate(widgetSchema(), gc, &pkg))
	require.NoError(t, g.Execute(gc, &pkg))

	b, err := os.ReadFile(filepath.Join(dir, "types.go"))
	require.NoError(t, err)

	return string(b)
}

func widgetPackage(keep bool, extra ...config.TypeConfig) config.PackageConfig {
	return config.PackageConfig{
		KeepRemovedFields: keep,
		Types:             append([]config.TypeConfig{{Name: "Widget"}, {Name: "Gadget"}, {Name: "Color"}}, extra...),
	}
}

const keptRemovedNote = "// Not in the NerdGraph schema; kept so existing code compiles."

func TestGenerate_KeepsRemovedFieldsAndEnumValues(t *testing.T) {
	out := regenerate(t, existingTypes, widgetPackage(true))

	assert.Contains(t, squash(out), keptRemovedNote+" AMBER Color", "an enum value the schema dropped")
	assert.Contains(t, out, "\tAMBER: \"AMBER\",\n")
	assert.Contains(t, squash(out), keptRemovedNote+" Color string `json:\"color,omitempty\"`", "a struct field the schema dropped")
	assert.Contains(t, squash(out), keptRemovedNote+" Weight int `json:\"weight,omitempty\"`", "in another struct")
	assert.Equal(t, 3, countOf(out, keptRemovedNote))
}

func TestGenerate_AFieldTheSchemaStillListsIsNotDuplicatedAndTakesTheSchemasType(t *testing.T) {
	out := regenerate(t, existingTypes, widgetPackage(true))

	assert.Equal(t, 1, countOf(out, "\tSize "), "one declaration of size")
	assert.Contains(t, squash(out), "Size int `json:\"size,omitempty\"`", "the schema says Int, the existing file String")
	assert.NotContains(t, squash(out), "Size string")
}

func TestGenerate_KeepsMembersInTheGeneratorsOrder(t *testing.T) {
	out := regenerate(t, existingTypes, widgetPackage(true))

	flat := squash(out)

	assert.Less(t, indexOf(flat, "Color string `json"), indexOf(flat, "Name string `json:\"name,omitempty\"` Size"), "Color sorts before Name in Widget")
	assert.Less(t, indexOf(flat, "Name string `json:\"name,omitempty\"` // Not in"), indexOf(flat, "Weight int"), "Name sorts before Weight in Gadget")
	assert.Less(t, indexOf(flat, "AMBER Color"), indexOf(flat, "BLUE Color"))
}

func TestGenerate_OffIsTheOutputTheGeneratorAlwaysMade(t *testing.T) {
	fresh := regenerate(t, "", widgetPackage(false))

	assert.Equal(t, fresh, regenerate(t, existingTypes, widgetPackage(false)), "the existing declarations the schema lacks are dropped")
	assert.NotContains(t, fresh, keptRemovedNote)
}

func TestGenerate_OnWithNothingRemovedIsTheOutputTheGeneratorAlwaysMade(t *testing.T) {
	fresh := regenerate(t, "", widgetPackage(false))

	assert.Equal(t, fresh, regenerate(t, fresh, widgetPackage(true)))
}

func TestGenerate_RegeneratingAKeptFileIsStable(t *testing.T) {
	first := regenerate(t, existingTypes, widgetPackage(true))

	assert.Equal(t, first, regenerate(t, first, widgetPackage(true)))
}

func TestGenerate_AKeepExistingTypeIsLeftAsWritten(t *testing.T) {
	out := regenerate(t, existingTypes, widgetPackage(true, config.TypeConfig{Name: "Widget", KeepExisting: true}))

	assert.Contains(t, squash(out), "Size string `json:\"size,omitempty\"`", "the pinned type is the existing text")
	assert.Contains(t, squash(out), "Color string `json:\"color,omitempty\"`")
	assert.Equal(t, 2, countOf(out, keptRemovedNote), "only Gadget.Weight and Color.AMBER are marked: the pinned type is not touched")
}

func TestGenerate_ASkippedFieldIsNotKept(t *testing.T) {
	pkg := widgetPackage(true)
	pkg.Types[0].SkipFields = []string{"Color"}

	out := regenerate(t, existingTypes, pkg)

	assert.NotContains(t, squash(out), "Color string `json")
	assert.Equal(t, 2, countOf(out, keptRemovedNote))
}

func countOf(s, sub string) int { return strings.Count(s, sub) }

func indexOf(s, sub string) int { return strings.Index(s, sub) }

// squash collapses whitespace, so a test is not about gofmt's column alignment.
func squash(s string) string { return strings.Join(strings.Fields(s), " ") }

func ref(kind schema.Kind, name string) schema.TypeRef { return schema.TypeRef{Kind: kind, Name: name} }

// managedSchema has an interface with two implementations. possible is what the
// schema lists for the package, as pkg/generate narrows it from include_implementations.
func managedSchema(possible ...string) *schema.Schema {
	var refs []schema.TypeRef
	for _, p := range possible {
		refs = append(refs, ref(schema.KindObject, p))
	}

	managedRef := ref(schema.KindInterface, "Managed")
	idField := schema.Field{Name: "id", Type: scalar("String")}

	return &schema.Schema{
		MutationType: &schema.Type{Name: "RootMutationType", Kind: schema.KindObject},
		Types: []*schema.Type{
			{Name: "Managed", Kind: schema.KindInterface, Fields: []schema.Field{idField}, PossibleTypes: refs},
			{Name: "McpServer", Kind: schema.KindObject, Interfaces: []schema.TypeRef{managedRef}, Fields: []schema.Field{idField, {Name: "url", Type: scalar("String")}}},
			{Name: "Skill", Kind: schema.KindObject, Interfaces: []schema.TypeRef{managedRef}, Fields: []schema.Field{idField}},
			{Name: "String", Kind: schema.KindScalar},
		},
	}
}

func managedTypes(t *testing.T, s *schema.Schema, narrowed bool) string {
	t.Helper()

	dir := t.TempDir()
	managed := config.TypeConfig{Name: "Managed"}

	if narrowed {
		managed.IncludeImplementations = []string{"McpServer"}
	}

	pkg := config.PackageConfig{Name: "demo", Path: dir, Types: []config.TypeConfig{managed, {Name: "McpServer"}}}
	gc := &config.GeneratorConfig{Name: "typegen", FileName: "types.go", TemplateDir: "../../templates/typegen"}
	g := &Generator{}

	require.NoError(t, g.Generate(s, gc, &pkg))
	require.NoError(t, g.Execute(gc, &pkg))

	b, err := os.ReadFile(filepath.Join(dir, "types.go"))
	require.NoError(t, err)

	return string(b)
}

func TestGenerate_ANarrowedInterfaceDecodesTheImplementationsItDoesNotListAsItsOwnStruct(t *testing.T) {
	out := managedTypes(t, managedSchema("McpServer"), true)

	assert.NotContains(t, out, "was not matched against all PossibleTypes")
	assert.Contains(t, squash(out), `case "McpServer": var interfaceType McpServer`)
	assert.Contains(t, squash(out), `return nil, fmt.Errorf("interface Managed did not include a __typename field for inspection: %s", keys) } // Not an implementation this package lists: decode the fields they all share. var interfaceType Managed err = json.Unmarshal(b, &interfaceType) if err != nil { return nil, err } var xxx ManagedInterface = &interfaceType return &xxx, nil }`)

	// It is Go: the decoder type-checks.
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "types.go", out, 0)
	require.NoError(t, err)

	conf := types.Config{Importer: importer.ForCompiler(fset, "source", nil)}
	_, err = conf.Check("demo", fset, []*ast.File{f}, nil)
	require.NoError(t, err)
}

func TestGenerate_AnInterfaceThatIsNotNarrowedKeepsItsError(t *testing.T) {
	out := managedTypes(t, managedSchema("McpServer", "Skill"), false)

	assert.Contains(t, out, `interface Managed was not matched against all PossibleTypes: %s`)
	assert.NotContains(t, out, "var interfaceType Managed\n")
}

func TestGenerate_ANarrowedInterfaceWithoutItsStructKeepsItsError(t *testing.T) {
	// The type is skipped, so the file has no struct for the interface to fall back to.
	dir := t.TempDir()
	pkg := config.PackageConfig{Name: "demo", Path: dir, Types: []config.TypeConfig{
		{Name: "Managed", IncludeImplementations: []string{"McpServer"}, SkipTypeCreate: true},
		{Name: "McpServer"},
	}}
	gc := &config.GeneratorConfig{Name: "typegen", FileName: "types.go", TemplateDir: "../../templates/typegen"}
	g := &Generator{}

	require.NoError(t, g.Generate(managedSchema("McpServer"), gc, &pkg))
	require.NoError(t, g.Execute(gc, &pkg))

	b, err := os.ReadFile(filepath.Join(dir, "types.go"))
	require.NoError(t, err)

	assert.NotContains(t, string(b), "var interfaceType Managed\n")
}
