package codegen

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func writeFiles(t *testing.T, files map[string]string) string {
	t.Helper()

	dir := t.TempDir()

	for name, content := range files {
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644))
	}

	return dir
}

func TestScanHandWritten_CollectsTypesAndMethodsOfHandWrittenFiles(t *testing.T) {
	t.Parallel()

	dir := writeFiles(t, map[string]string{
		"extra.go": `package p

import "encoding/json"

type Auth struct{}

type (
	AuthInterface interface{ ImplementsAuth() }
	Token         string
)

func (x *Auth) UnmarshalJSON(b []byte) error { return json.Unmarshal(b, x) }
func (x Auth) String() string                { return "" }
func helper()                                {}
`,
	})

	got, err := ScanHandWritten(dir)
	require.NoError(t, err)

	assert.Equal(t, map[string]bool{"Auth": true, "AuthInterface": true, "Token": true}, got.Types)
	assert.Equal(t, map[string]bool{"Auth.UnmarshalJSON": true, "Auth.String": true}, got.Methods)
}

func TestScanHandWritten_LeavesOutGeneratedAndTestFiles(t *testing.T) {
	t.Parallel()

	dir := writeFiles(t, map[string]string{
		"types.go":      "// Code generated by tutone: DO NOT EDIT\npackage p\n\ntype Generated struct{}\n\nfunc (x *Generated) UnmarshalJSON(b []byte) error { return nil }\n",
		"other.go":      "// Code generated by something. DO NOT EDIT.\npackage p\n\ntype Other struct{}\n",
		"types_test.go": "package p\n\ntype Fixture struct{}\n",
		"notes.txt":     "type NotGo struct{}",
		"hand.go":       "package p\n\ntype Hand struct{}\n",
	})

	got, err := ScanHandWritten(dir)
	require.NoError(t, err)

	assert.Equal(t, map[string]bool{"Hand": true}, got.Types)
	assert.Empty(t, got.Methods)
}

func TestScanHandWritten_AFileThatMerelyMentionsTheHeaderIsHandWritten(t *testing.T) {
	t.Parallel()

	dir := writeFiles(t, map[string]string{
		"late.go": "package p\n\n// Code generated by tutone: DO NOT EDIT\ntype Late struct{}\n",
		"body.go": "package p\n\nvar s = \"Code generated by tutone: DO NOT EDIT\"\n\ntype Body struct{}\n",
	})

	got, err := ScanHandWritten(dir)
	require.NoError(t, err)

	assert.Equal(t, map[string]bool{"Late": true, "Body": true}, got.Types)
}

func TestScanHandWritten_MissingDirectoryHasNothing(t *testing.T) {
	t.Parallel()

	got, err := ScanHandWritten(filepath.Join(t.TempDir(), "absent"))
	require.NoError(t, err)

	assert.Empty(t, got.Types)
	assert.Empty(t, got.Methods)
}

func TestScanHandWritten_FileThatDoesNotParseIsAnErrorNamingIt(t *testing.T) {
	t.Parallel()

	dir := writeFiles(t, map[string]string{"broken.go": "package p\n\nfunc ("})

	_, err := ScanHandWritten(dir)
	require.Error(t, err)
	assert.Contains(t, err.Error(), "broken.go")
}

func TestScanHandWritten_SubdirectoriesAreNotScanned(t *testing.T) {
	t.Parallel()

	dir := writeFiles(t, map[string]string{"hand.go": "package p\n\ntype Hand struct{}\n"})
	require.NoError(t, os.Mkdir(filepath.Join(dir, "sub.go"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(dir, "sub.go", "inner.go"), []byte("package q\n\ntype Inner struct{}\n"), 0o644))

	got, err := ScanHandWritten(dir)
	require.NoError(t, err)

	assert.Equal(t, map[string]bool{"Hand": true}, got.Types)
}

func TestScanHandWritten_PathThatIsNotADirectoryIsAnError(t *testing.T) {
	t.Parallel()

	dir := writeFiles(t, map[string]string{"file.go": "package p\n"})

	_, err := ScanHandWritten(filepath.Join(dir, "file.go"))
	require.Error(t, err)
}
