func TestWriteFile_RenamedReceiverStillMatchesTheExistingMethod(t *testing.T) {
	t.Parallel()

	tmplDir, tmplName := writeTemplate(t, legacyTemplate)
	out := t.TempDir()
	dest := filepath.Join(out, "organization_api.go")

	// What the repository has: the receiver the config names, one pinned method and one by hand.
	existing := `package organization

// Get was fixed by hand.
// DO NOT REGENERATE
func (a *OrganizationManagement) Get(other *Organization) *Organization { return nil }

func (a *OrganizationManagement) ByHand() {}
`
	require.NoError(t, os.WriteFile(dest, []byte(existing), 0o600))

	c := CodeGen{
		TemplateDir:         tmplDir,
		TemplateName:        tmplName,
		DestinationDir:      out,
		DestinationFile:     dest,
		ReceiverRenames:     map[string]string{"Organization": "OrganizationManagement"},
		PreserveHandWritten: true,
	}
	require.NoError(t, c.WriteFile(fakeGenerator{Name: "organization"}))

	got, err := os.ReadFile(dest)
	require.NoError(t, err)

	// The rename comes before the merge, so the pinned method replaces the generator's
	// instead of sitting next to it.
	assert.Equal(t, 1, strings.Count(string(got), "Get("), "one Get, not the pinned and the generated")
	assert.Contains(t, string(got), "return nil", "the pinned text won")
	assert.Contains(t, string(got), "func (a *OrganizationManagement) ByHand()")
}

func TestWriteFile_KeepNamesKeepTheExistingDeclaration(t *testing.T) {
	t.Parallel()

	tmplDir, tmplName := writeTemplate(t, "package demo\n\ntype {{.Name}} struct{ Generated bool }\n\ntype Other struct{ Generated bool }\n")
	out := t.TempDir()
	dest := filepath.Join(out, "types.go")
	existing := "package demo\n\ntype Fresh struct{ Mine bool }\n\ntype Other struct{ Old bool }\n"

	require.NoError(t, os.WriteFile(dest, []byte(existing), 0o600))

	c := CodeGen{
		TemplateDir:         tmplDir,
		TemplateName:        tmplName,
		DestinationDir:      out,
		DestinationFile:     dest,
		PreserveHandWritten: true,
		KeepNames:           []string{"Fresh"},
	}
	require.NoError(t, c.WriteFile(fakeGenerator{Name: "Fresh"}))

	got, err := os.ReadFile(dest)
	require.NoError(t, err)

	assert.Contains(t, string(got), "Mine bool")
	assert.NotContains(t, string(got), "Old bool", "a type that is not kept is regenerated")
	assert.Contains(t, string(got), "type Other struct{ Generated bool }")

	// Without preserving there is nothing to keep it from.
	c.PreserveHandWritten = false
	require.NoError(t, os.WriteFile(dest, []byte(existing), 0o600))
	require.NoError(t, c.WriteFile(fakeGenerator{Name: "Fresh"}))

	got, err = os.ReadFile(dest)
	require.NoError(t, err)
	assert.NotContains(t, string(got), "Mine bool")
}

